CREATE OR REPLACE FUNCTION public.get_student_auth(p_nis text)
RETURNS TABLE (nis text, name text, class text, batch text, rombel text)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN QUERY SELECT s.nis, s.name, s.class, s.batch, s.rombel
    FROM students s WHERE s.nis = p_nis LIMIT 1;
END; $$;

CREATE OR REPLACE FUNCTION public.check_auth_blocked(p_identifier text)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE attempts int;
BEGIN
  SELECT failed_attempts INTO attempts FROM login_attempts WHERE identifier = p_identifier;
  RETURN COALESCE(attempts, 0) >= 5;
END; $$;

CREATE OR REPLACE FUNCTION public.record_login_failure(p_identifier text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE exists_flag boolean;
BEGIN
  SELECT EXISTS (SELECT 1 FROM students WHERE nis = p_identifier)
      OR EXISTS (SELECT 1 FROM users WHERE email = p_identifier) INTO exists_flag;
  IF NOT exists_flag THEN RETURN; END IF;
  INSERT INTO login_attempts (identifier, failed_attempts, last_failed_at)
  VALUES (p_identifier, 1, now())
  ON CONFLICT (identifier) DO UPDATE
  SET failed_attempts = login_attempts.failed_attempts + 1, last_failed_at = now();
END; $$;

CREATE OR REPLACE FUNCTION public.reset_login_attempts(p_identifier text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM login_attempts WHERE identifier = p_identifier;
END; $$;

CREATE OR REPLACE FUNCTION public.get_my_profile(p_nis text)
RETURNS SETOF students LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN QUERY SELECT * FROM students WHERE nis = p_nis LIMIT 1;
END; $$;

CREATE OR REPLACE FUNCTION public.get_my_classmates(p_nis text)
RETURNS TABLE (id uuid, name text, nis text, class text, rombel text, batch text, status text)
LANGUAGE plpgsql STABLE AS $$
DECLARE v_class text;
BEGIN
  SELECT s.class INTO v_class FROM students s WHERE s.nis = p_nis LIMIT 1;
  IF v_class IS NULL THEN RETURN; END IF;
  RETURN QUERY SELECT s.id, s.name, s.nis, s.class, s.rombel, s.batch, s.status
    FROM students s WHERE s.class = v_class ORDER BY s.name;
END; $$;

CREATE OR REPLACE FUNCTION public.get_public_teachers()
RETURNS TABLE (id uuid, name text, role text, subject text, wali_kelas text, angkatan_wali text, rombel_wali text)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN QUERY SELECT t.id, t.name, t.role, t.subject, t.wali_kelas, t.angkatan_wali, t.rombel_wali
    FROM teachers t ORDER BY t.name;
END; $$;

CREATE OR REPLACE FUNCTION public.get_my_rapor(p_nis text)
RETURNS TABLE (id bigint, student_id uuid, category text, score text, notes text,
  material text, image_url text, semester int, report_date timestamptz,
  is_published boolean, created_at timestamptz,
  student_name text, student_nis text, student_class text, student_rombel text, student_batch text)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN QUERY SELECT a.id, a.student_id, a.category, a.score, a.notes,
    a.material, a.image_url, a.semester, a.report_date, a.is_published, a.created_at,
    s.name, s.nis, s.class, s.rombel, s.batch
    FROM assessments a JOIN students s ON s.id = a.student_id
    WHERE s.nis = p_nis AND a.is_published IS TRUE
    ORDER BY a.created_at DESC;
END; $$;

CREATE OR REPLACE FUNCTION public.get_my_attendance(p_nis text)
RETURNS TABLE (date date, status text)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN QUERY SELECT a.date, a.status FROM attendance a
    JOIN students s ON s.id = a.student_id
    WHERE s.nis = p_nis ORDER BY a.date DESC;
END; $$;

CREATE OR REPLACE FUNCTION public.get_student_stats_summary()
RETURNS TABLE (batch text, class_name text, total_count bigint, lulus_count bigint)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  IF NOT public.is_staff() THEN RAISE EXCEPTION 'Akses ditolak'; END IF;
  RETURN QUERY SELECT s.batch, s.class, COUNT(*),
    COUNT(*) FILTER (WHERE s.status = 'Lulus')
    FROM students s GROUP BY s.batch, s.class;
END; $$;

CREATE OR REPLACE FUNCTION public.verify_user_by_admin(p_user_id uuid, p_role text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Akses ditolak: hanya Admin'; END IF;
  IF p_role NOT IN ('Guru', 'Admin') THEN RAISE EXCEPTION 'Role tidak valid'; END IF;
  UPDATE public.profiles SET is_verified = true, role = p_role WHERE id = p_user_id;
END; $$;

CREATE OR REPLACE FUNCTION public.delete_user_by_admin(target_user_id uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Akses ditolak: hanya Admin'; END IF;
  DELETE FROM public.profiles WHERE id = target_user_id;
  DELETE FROM public.users WHERE id = target_user_id;
END; $$;

