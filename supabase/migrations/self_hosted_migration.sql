-- ==========================================================
-- 3. HELPER: get current user id dari session variable
-- ==========================================================
-- App harus SET app.current_user_id = '<uuid>' sebelum query.
-- Contoh: SET app.current_user_id = '11111111-1111-1111-1111-111111111111';

CREATE OR REPLACE FUNCTION public.current_user_id()
RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT current_setting('app.current_user_id', true)::uuid;
$$;

CREATE OR REPLACE FUNCTION public.is_staff()
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE id = public.current_user_id()
      AND role IN ('Admin', 'Guru', 'Super Admin')
  );
$$;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE id = public.current_user_id()
      AND role IN ('Admin', 'Super Admin')
  );
$$;

-- Trigger auto-create profiles saat insert users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, role, is_verified)
  VALUES (NEW.id, NEW.email, NEW.full_name, 'Guru', false)
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_user_created ON public.users;
CREATE TRIGGER on_user_created AFTER INSERT ON public.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

